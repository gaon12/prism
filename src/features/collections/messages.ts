export type Key = keyof typeof messages;
const indexes: Record<Language, number> = { ko: 0, en: 1, 'zh-CN': 2, 'zh-TW': 3, ja: 4 };
export function libraryText(
  language: Language,
  key: Key,
  values?: Record<string, string | number>,
) {
  let text: string = messages[key][indexes[language]] ?? messages[key][1];
  for (const [name, value] of Object.entries(values ?? {}))
    text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export function failureKey(cause: unknown): Key {
  const code =
    typeof cause === 'object' && cause && 'code' in cause ? String(cause.code) : 'storage';
  return code in messages ? (code as Key) : 'storage';
}
