const languageIndex: Record<Language, number> = { ko: 0, en: 1, 'zh-CN': 2, 'zh-TW': 3, ja: 4 };
export type DocumentMessage = keyof typeof messages;
export function documentText(
  language: Language,
  key: DocumentMessage,
  values?: Record<string, string | number>,
) {
  let text = messages[key][languageIndex[language]] ?? messages[key][1];
  if (values)
    for (const [name, value] of Object.entries(values))
      text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
