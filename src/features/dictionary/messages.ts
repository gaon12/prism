export type DictionaryMessageKey = keyof typeof messages;
const locales: Language[] = ['ko', 'en', 'zh-CN', 'zh-TW', 'ja'];
export function dictText(
  locale: Language,
  key: DictionaryMessageKey,
  values: Record<string, string | number> = {},
) {
  const text = messages[key][locales.indexOf(locale)] ?? messages[key][1];
  return text.replace(/\{(\w+)\}/g, (match, token: string) => String(values[token] ?? match));
}
export function dictionaryLanguageName(locale: Language, language: string) {
  return ['ko', 'en', 'zh', 'ja'].includes(language)
    ? dictText(locale, language as 'ko' | 'en' | 'zh' | 'ja')
    : language;
}
const errors: Record<string, DictionaryMessageKey> = {
  network: 'errorNetwork',
  notFound: 'errorNotFound',
  rateLimited: 'errorRateLimited',
  server: 'errorServer',
  invalidResponse: 'errorInvalidResponse',
  input: 'errorInput',
  storage: 'errorStorage',
  busy: 'errorBusy',
  limit: 'errorLimit',
  cancelled: 'cancelled',
};
export function dictionaryErrorText(locale: Language, code: string) {
  return dictText(locale, errors[code] ?? 'errorGeneric');
}
